const hatch = (shape: "tri" | "circ" | "sq" | "star" | "eight" | "U" | "diam" | "L" | "D", kind: "diag" | "horiz" | "vert" = "diag") => {
  const h = makeHatch(kind);
  let body = "";
  if (shape === "tri") body = `<polygon points="0,-9 -9,7 9,7" fill="${h.fill}" stroke="currentColor" stroke-width="1.6"/>`;
  else if (shape === "circ") body = `<circle cx="0" cy="0" r="7.5" fill="${h.fill}" stroke="currentColor" stroke-width="1.6"/>`;
  else if (shape === "sq") body = `<rect x="-7" y="-7" width="14" height="14" fill="${h.fill}" stroke="currentColor" stroke-width="1.6"/>`;
  else if (shape === "diam") body = `<polygon points="0,-9 8,0 0,9 -8,0" fill="${h.fill}" stroke="currentColor" stroke-width="1.6"/>`;
  else if (shape === "eight") body = `<circle cx="0" cy="-4" r="4" fill="${h.fill}" stroke="currentColor" stroke-width="1.5"/><circle cx="0" cy="4" r="4" fill="${h.fill}" stroke="currentColor" stroke-width="1.5"/>`;
  else if (shape === "star") body = `<polygon points="0,-9 2.5,-2.5 9,-2 4,2.5 6,9 0,5 -6,9 -4,2.5 -9,-2 -2.5,-2.5" fill="${h.fill}" stroke="currentColor" stroke-width="1.4"/>`;
  else if (shape === "L") body = `<polygon points="-6,-8 -2,-8 -2,4 6,4 6,8 -6,8" fill="${h.fill}" stroke="currentColor" stroke-width="1.5"/>`;
  else if (shape === "D") body = `<path d="M-5-8H0A7 8 0 0 1 0 8H-5Z" fill="${h.fill}" stroke="currentColor" stroke-width="1.6"/>`;
  else body = `<path d="M-7-7V2A7 6 0 0 0 7 2V-7H3V2A3 3 0 0 1-3 2V-7Z" fill="${h.fill}" stroke="currentColor" stroke-width="1.5"/>`;
  return S(`${h.def}${body}`);
};

